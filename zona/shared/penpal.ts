/** Чем кончилась переписка. */
export function penEnding(s: { scam: boolean; love: number; suspect: number; paid: number }): PenEnding {
  if (s.scam) return s.paid > 0 ? 'scam' : s.suspect >= 2 ? 'caught' : 'gone';
  if (s.love >= 12) return 'wedding';
  if (s.love >= 6) return 'wait';
  return 'gone';
}
