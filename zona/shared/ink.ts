export const inkQuality = (skill: number, acc: number) => Math.round(Math.max(0, Math.min(100, skill * 0.5 + Math.max(0, Math.min(1, acc)) * 50)));

export const inkRank = (skill: number) => (skill >= 80 ? 'Художник' : skill >= 50 ? 'Мастер' : skill >= 20 ? 'Кольщик' : 'Ученик');
